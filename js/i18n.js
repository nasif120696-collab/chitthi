export function getLang() {
  return localStorage.getItem("chitthi_lang") || "bn";
}

export function setLang(lang) {
  localStorage.setItem("chitthi_lang", lang);
  applyTranslations(lang);
}

export function toggleLang() {
  const next = getLang() === "bn" ? "en" : "bn";
  setLang(next);
  return next;
}

export function t(key) {
  const lang = getLang();
  return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || TRANSLATIONS.bn[key] || key;
}

export function applyTranslations(lang = getLang()) {
  document.documentElement.lang = lang === "bn" ? "bn" : "en";
  if (lang === "en") {
    document.body.classList.add("lang-en");
  } else {
    document.body.classList.remove("lang-en");
  }

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) {
      el.textContent = TRANSLATIONS[lang][key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) {
      el.setAttribute("placeholder", TRANSLATIONS[lang][key]);
    }
  });

  const langBtn = document.getElementById("lang-toggle-btn");
  if (langBtn) {
    langBtn.textContent = lang === "bn" ? "বাংলা | EN" : "EN | বাংলা";
  }
}
